public sealed record EvaluationRow(
    string Method,
    double PrecisionAt5,
    double RecallAt5,
    double NdcgAt5,
    double PrecisionAt10,
    double RecallAt10,
    double NdcgAt10,
    double HitRateAt10,
    double Coverage,
    double Diversity);

public sealed record EvaluationReport(
    int Events,
    int Personas,
    int TestUsers,
    int TrainInteractions,
    int TestInteractions,
    int TestSeed,
    int ValidationSeed,
    double Gamma,
    double Mu,
    double Prior,
    IReadOnlyList<OfflineEvaluation.TuningPoint> Grid,
    IReadOnlyList<EvaluationRow> Rows,
    int ColdStartUsers,
    IReadOnlyList<EvaluationRow> ColdStartRows)
{
